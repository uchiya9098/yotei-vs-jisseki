-- ============================================================
-- 追加マイグレーション：実績時間の「確認済み」フラグ（見積もり参考値の信頼性のため）
--
-- 過去の「転記」操作では、予定の時刻が実績の時間としてコピーされていた期間があり、
-- 既存の実績時間が「本人が入力・確認したもの」か「予定のコピー」かは判別できない。
-- そこで time_confirmed を追加し、**既存の行はすべて false（未確認）** にする。
--   - 既存の時間・メモ・理由などの値は一切変更・削除しない。
--   - 見積もりの参考時間には time_confirmed = true の実績だけを使う。
--   - 何度実行しても安全（idempotent）。
--
-- 適用: Supabase の SQL Editor で実行（001〜005 の後）。
-- ※ アプリを更新する前、または同時に実行してください。未適用のままだと
--   確認済みの保存と、ゲストデータの実績のクラウド同期が失敗します。
-- ============================================================

alter table public.actual_logs
  add column if not exists time_confirmed boolean not null default false;
